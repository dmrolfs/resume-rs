"""Rebuilds table.rs from Python's own `str` results. Run: python3 generate.py > table.rs

The text is synthetic; nothing here comes from a resume or a job description. Python decides every expected value, so the
Rust test checks Rust against Python and not Rust against itself. The whitespace list is read from `str.isspace` over
the whole of Unicode, then every member and its neighbours are included as cases.
"""
import json
import random
import re
import sys

random.seed(5)


def rust(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append('\\u{%x}' % o)
    return '"' + ''.join(out) + '"'


def occurrences(haystack, needle):
    return len(list(re.finditer('(?=' + re.escape(needle) + ')', haystack))) if needle else 0


spaces = [chr(c) for c in range(0x110000) if chr(c).isspace()]
neighbours = sorted({chr(c + d) for ch in spaces for c in [ord(ch)] for d in (-1, 1)
                     if 0 <= c + d < 0x110000 and not chr(c + d).isspace()})
base = ["", "plain ascii", "naïve café ñ", "猫 and 犬", "😀 a 😀", "e\u0301", "\U0001F469\u200D\U0001F469",
        "line\r\nbreak\rlone\nlf", "\u001c\u001d\u001e\u001f x \u0085\u00a0",
        "\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a hi \u2028\u2029\u202f\u205f\u3000",
        "\u200bzw\ufeff", "\u180e mongolian", "aaaa", "abababab", "\u1680ogham\u1680",
        "\t\n\v\f\r pad \t\n\v\f\r", "ǅ ß İ ﬁ", "𝔘𝔫𝔦𝔠𝔬𝔡𝔢", "\U0010ffff end", "a\u0000b",
        "\u007f\u0080 \u07ff\u0800 \uffff\U00010000"]
# every Python space on its own, padded around a letter, so each is checked and none depends on a neighbour
base += [f"{ch}x{ch}" for ch in spaces]
# the characters just outside each space range must not strip
base += [f"{ch}x{ch}" for ch in neighbours]
pool = list("aé猫😀\u0301\u200d\u00a0\u3000\u0085\u001c\r\n \t.ß") + ["\U0001F600", "\u2028"]
base += [''.join(random.choice(pool) for _ in range(random.randint(1, 14))) for _ in range(40)]

rows = []
for t in base:
    needles = set()
    for k in (1, 2, 3):
        for i in range(0, max(1, len(t) - k + 1), max(1, len(t) // 4 or 1)):
            if t[i:i + k]:
                needles.add(t[i:i + k])
    needles |= {"aa", "ab", "a", "", " ", "\r\n"}
    n = sorted(needles)[:8]
    length = len(t)
    slices = sorted((a, b, t[a:b]) for a, b in {(0, 0), (0, length), (length, length), (0, min(1, length)),
                                                (max(0, length - 1), length), (length // 3, length // 2), (length // 2, length)}
                    if a <= b <= length)
    rows.append((t, length, len(t.strip()), [(x, occurrences(t, x)) for x in n], slices))

print(f'// Generated by `python3 generate.py` ({sys.version.split()[0]}) from synthetic text; do not edit by hand.')
print(f'// {len(spaces)} Python whitespace characters, {len(neighbours)} neighbours, {len(rows)} cases.')
print('const CASES: &[Case] = &[')
for t, length, stripped, needles, slices in rows:
    print('    (%s, %d, %d, &[%s], &[%s]),' % (
        rust(t), length, stripped,
        ', '.join('(%s, %d)' % (rust(n), c) for n, c in needles),
        ', '.join('(%d, %d, %s)' % (a, b, rust(s)) for a, b, s in slices)))
print('];')
